/// When every provisional ID collided (the text of the ticket, with the noun of the epic).
pub const NO_UNIQUE_ID_MESSAGE: &str =
    "Não consegui gerar um ID provisório único para o épico. Tente de novo.";

/// Creates an epic of the project: `jira_input` trimmed is the Jira ID, or, when empty, a
/// provisional short ID is generated by the database (the rules of a ticket: `tickets::create`).
pub fn create(db: &Db, project_id: i64, title: &str, jira_input: &str) -> Result<Epic, String> {
    create_with(db, project_id, title, jira_input, &mut || {
        db.random_short_id()
    })
}

/// `create` with the generator of provisional IDs received by parameter (the tests make it
/// collide).
pub fn create_with(
    db: &Db,
    project_id: i64,
    title: &str,
    jira_input: &str,
    generate: &mut dyn FnMut() -> rusqlite::Result<String>,
) -> Result<Epic, String> {
    let title = tickets::check_title_of(title, "épico")?;
    tickets::create_key_with(
        db,
        project_id,
        jira_input,
        NO_UNIQUE_ID_MESSAGE,
        generate,
        &mut |key, provisional| db.insert_epic(project_id, key, provisional, title),
    )
}

/// The status message after a creation.
pub fn created_message(epic: &Epic) -> String {
    if epic.is_provisional {
        format!(
            "Épico criado com o ID provisório {}: {}.",
            epic.key, epic.title
        )
    } else {
        format!("Épico criado: {} — {}.", epic.key, epic.title)
    }
}

/// Changes the title of the epic (the rule of the creation); the ID never changes here.
pub fn rename(db: &Db, epic: &Epic, title: &str) -> Result<String, String> {
    let title = tickets::check_title_of(title, "épico")?;
    still_there(epic, db.update_epic_title(epic.id, title))?;
    Ok(format!("Título atualizado: {}.", epic.key))
}

/// The refusal of hiding an epic whose branch has `active` agents (of any nick).
pub fn active_message(epic: &Epic, active: i64) -> String {
    let agents = count_of(active, "agente ativo", "agentes ativos");
    format!(
        "O épico {} tem {agents} (no épico ou nos tickets dele). Encerre-os antes de ocultar.",
        epic.key
    )
}

/// Hides the epic and so its whole branch (decision 8 of NS-40): the `hidden_at` of its tickets
/// does not change. Refused while the epic or a ticket of it has an `active` agent, by one
/// conditioned UPDATE (`Db::hide_epic`).
pub fn hide(db: &Db, epic: &Epic) -> Result<String, String> {
    match db.hide_epic(epic.id) {
        Ok(EpicHide::Done) => Ok(format!(
            "Épico ocultado: {}. O ramo inteiro continua no banco e pode ser restaurado (f mostra \
             os ocultos).",
            epic.key
        )),
        Ok(EpicHide::Gone) => Err(gone_message(epic)),
        Ok(EpicHide::Active(active)) => Err(active_message(epic, active)),
        Ok(EpicHide::Changed) => Err(format!(
            "O épico {} mudou enquanto era ocultado. Tente de novo.",
            epic.key
        )),
        Err(err) => Err(db_error_message(&err)),
    }
}

/// Shows a hidden epic (and its branch) again: each ticket comes back as it was.
pub fn restore(db: &Db, epic: &Epic) -> Result<String, String> {
    still_there(epic, db.restore_epic(epic.id))?;
    Ok(format!("Épico restaurado: {}.", epic.key))
}

/// Completes the epic (NS-54, D2): only with tickets and every one of them done, the hidden ones
/// included, by one conditioned UPDATE (`Db::complete_epic`). No confirmation: `c` opens it again.
/// With `hide_done` (the filter `d` of the tree is on), the message says it leaves the tree.
pub fn complete(db: &Db, epic: &Epic, hide_done: bool) -> Result<String, String> {
    match db.complete_epic(epic.id) {
        Ok(EpicCompletion::Done) => {
            let mut message = format!("Épico concluído: {}.", epic.key);
            if hide_done {
                message.push_str(" Ele sai da árvore (d mostra os concluídos).");
            }
            Ok(message)
        }
        Ok(EpicCompletion::Gone) => Err(gone_message(epic)),
        Ok(EpicCompletion::AlreadyDone) => Err(format!("O épico {} já está concluído.", epic.key)),
        Ok(EpicCompletion::Empty) => Err(format!(
            "O épico {} não tem tickets e não pode ser concluído.",
            epic.key
        )),
        Ok(EpicCompletion::Pending { pending, hidden }) => {
            Err(pending_message(epic, pending, hidden))
        }
        Err(err) => Err(db_error_message(&err)),
    }
}

/// The refusal of completing an epic with tickets not done (the plural of `count_of`). The hidden
/// ones among them are told apart, with the key that shows them (the mold of the refusal of a
/// duplicate key): without the `f` the tree does not list them, and the epic looks done (found in
/// the validation of the NS-54 with the operator's database).
pub fn pending_message(epic: &Epic, pending: i64, hidden: i64) -> String {
    let tickets = count_of(pending, "ticket não concluído", "tickets não concluídos");
    let hidden = match hidden {
        0 => String::new(),
        _ if hidden == pending && pending == 1 => " (oculto; f mostra os ocultos)".to_string(),
        _ if hidden == pending => " (ocultos; f mostra os ocultos)".to_string(),
        _ => format!(
            " ({}; f mostra os ocultos)",
            count_of(hidden, "oculto", "ocultos")
        ),
    };
    format!("O épico {} ainda tem {tickets}{hidden}.", epic.key)
}

/// Opens a done epic again by hand (NS-54, D2), with no confirmation (the mold of `restore`).
pub fn reopen(db: &Db, epic: &Epic) -> Result<String, String> {
    match db.reopen_epic(epic.id) {
        Ok(true) => Ok(format!("Épico reaberto: {}.", epic.key)),
        Ok(false) => match db.get_epic(epic.id) {
            Ok(Some(_)) => Err(format!("O épico {} já está aberto.", epic.key)),
            Ok(None) => Err(gone_message(epic)),
            Err(err) => Err(db_error_message(&err)),
        },
        Err(err) => Err(db_error_message(&err)),
    }
}

/// The notice of a done epic opened again by a write of the ticket `ticket_key` (NS-54, D3).
pub fn reopened_notice(epic_key: &str, ticket_key: &str) -> String {
    format!("O épico {epic_key} foi reaberto: o ticket {ticket_key} não está concluído.")
}

/// `message`, with the notice of the reopening after it only when the write opened an epic again
/// (`reopened`: its key); otherwise the message of before, byte by byte.
pub fn with_reopened(message: String, reopened: Option<&str>, ticket_key: &str) -> String {
    match reopened {
        Some(epic_key) => format!("{message} {}", reopened_notice(epic_key, ticket_key)),
        None => message,
    }
}

fn still_there(epic: &Epic, updated: rusqlite::Result<bool>) -> Result<(), String> {
    match updated {
        Ok(true) => Ok(()),
        Ok(false) => Err(gone_message(epic)),
        Err(err) => Err(db_error_message(&err)),
    }
}

/// The epic is no longer in the database.
pub fn gone_message(epic: &Epic) -> String {
    format!("O épico {} não existe mais no banco.", epic.key)
}

/// The refusal of `g` in a hidden epic, or in a ticket of one (decision 9 of NS-40).
pub fn hidden_message(epic: &Epic) -> String {
    format!(
        "O épico {} está oculto. Restaure-o (o) para abrir um agente.",
        epic.key
    )
}

/// Steps 1 to 5 of "Editar ID" of an epic (the rules of the ticket, NS-36): refused with an
/// `active` agent of the epic (its prompt cites the folder); the agents of its tickets do not
/// count (their folder is the ticket's). Returns the new ID.
pub fn check_new_id(db: &Db, epic: &Epic, input: &str) -> Result<String, String> {
    tickets::check_new_key(
        db,
        epic.project_id,
        &epic.key,
        input,
        "épico",
        Owner::Epic(epic.id),
    )
}

/// Edits the ID of the epic of the project at `project`: the folder `.nick/docs/<old>/` renamed
/// first, then the database, the rename undone when the database fails.
pub fn edit_id(db: &Db, project: &Path, epic: &Epic, input: &str) -> Result<String, String> {
    edit_id_with(db, project, epic, input, &mut |old, new| {
        db.update_epic_key(epic.id, old, new)
    })
}

/// `edit_id` with the write of the database received by parameter (the tests make it fail).
pub fn edit_id_with(
    db: &Db,
    project: &Path,
    epic: &Epic,
    input: &str,
    update: &mut dyn FnMut(&str, &str) -> rusqlite::Result<bool>,
) -> Result<String, String> {
    let new = check_new_id(db, epic, input)?;
    tickets::rename_key_with(
        db,
        project,
        epic.project_id,
        &epic.key,
        &new,
        &gone_message(epic),
        "o épico",
        update,
    )
}

/// Moves `ticket` into the epic `to`, or out of its epic (None) (decision 11 of NS-40): only the
/// database changes (`Db::set_ticket_epic`, its only caller), no file is touched and no agent is
/// told, even an active one. The same place is refused, and so is an epic of another project. A
/// ticket not done into a done epic opens it again, with the notice (NS-54, D3).
pub fn move_ticket(db: &Db, ticket: &Ticket, to: Option<&Epic>) -> Result<String, String> {
    if ticket.epic_id == to.map(|epic| epic.id) {
        return Err(format!("O ticket {} já está aí.", ticket.key));
    }
    if let Some(epic) = to
        && epic.project_id != ticket.project_id
    {
        return Err(format!(
            "O épico {} é de outro projeto: o ticket {} só vai para um épico do projeto dele.",
            epic.key, ticket.key
        ));
    }
    // The epic it leaves, for the message (read before the move).
    let from = match ticket.epic_id {
        Some(id) => db.get_epic(id).map_err(|err| db_error_message(&err))?,
        None => None,
    };
    match db.set_ticket_epic(ticket.id, to.map(|epic| epic.id)) {
        Ok((true, reopened)) => {
            let message = match (to, from) {
                (Some(epic), _) => {
                    format!("Ticket {} movido para o épico {}.", ticket.key, epic.key)
                }
                (None, Some(epic)) => {
                    format!("Ticket {} tirado do épico {}.", ticket.key, epic.key)
                }
                (None, None) => format!("Ticket {} tirado do épico.", ticket.key),
            };
            Ok(with_reopened(message, reopened.as_deref(), &ticket.key))
        }
        Ok((false, _)) => match db.get_ticket(ticket.id) {
            Ok(None) => Err(tickets::gone_message(ticket)),
            Ok(Some(_)) => {
                let Some(to) = to else {
                    return Err(tickets::gone_message(ticket));
                };
                // The epic read again: gone, or hidden by another nick with the list open.
                match db.get_epic(to.id) {
                    Ok(Some(now)) if now.hidden_at.is_some() => {
                        Err(format!("O épico {} está oculto.", now.key))
                    }
                    Ok(_) => Err(gone_message(to)),
                    Err(err) => Err(db_error_message(&err)),
                }
            }
            Err(err) => Err(db_error_message(&err)),
        },
        Err(err) => Err(db_error_message(&err)),
    }
}

