//! The rules of the epics of a project (NS-40), with no screen, in the mold of tickets.rs: an
//! optional level between the project and the ticket that holds long conversations (agents only
//! of PO and Tech Leader), with the ID and the title of a ticket and no stage. Creating, renaming,
//! hiding (the whole branch) and restoring, editing the ID, and moving a ticket in, between and out
//! of the epics. Everything lives only in the database, with one exception: `edit_id` renames
//! `.nick/docs/<old ID>/` to `.nick/docs/<new ID>/` (docs.rs), as the "Editar ID" of a ticket;
//! moving a ticket touches no file. The errors are the messages for the status bar, in PT-BR.

use std::path::Path;

