    /// A generator that returns `ids` in order and counts the calls.
    fn scripted(
        ids: &[&str],
    ) -> (
        impl FnMut() -> rusqlite::Result<String>,
        std::rc::Rc<std::cell::Cell<usize>>,
    ) {
        let calls = std::rc::Rc::new(std::cell::Cell::new(0));
        let counter = std::rc::Rc::clone(&calls);
        let ids: Vec<String> = ids.iter().map(|s| s.to_string()).collect();
        let generate = move || {
            let n = counter.get();
            counter.set(n + 1);
            Ok(ids[n.min(ids.len() - 1)].clone())
        };
        (generate, calls)
    }

