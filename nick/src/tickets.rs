    /// The verdict of the real `jira_id_valid` of auto_scrum.sh for `id`, under `lc_all`.
    fn bash_verdict(id: &str, lc_all: Option<&str>) -> bool {
        let script = concat!(env!("CARGO_MANIFEST_DIR"), "/../auto_scrum/auto_scrum.sh");
        assert!(Path::new(script).is_file(), "{script}");
        let mut command = std::process::Command::new("bash");
        command
            .args(["-c", r#"source "$1"; jira_id_valid "$2""#, "_", script, id])
            .stdin(std::process::Stdio::null());
        if let Some(lc) = lc_all {
            command.env("LC_ALL", lc);
        }
        let out = command.output().expect("bash runs");
        assert!(
            out.stdout.is_empty() && out.stderr.is_empty(),
            "{id:?}: {out:?}"
        );
        match out.status.code() {
            Some(0) => true,
            Some(1) => false,
            other => panic!("{id:?}: unexpected exit {other:?}: {out:?}"),
        }
    }

