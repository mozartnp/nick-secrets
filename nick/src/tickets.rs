//! The rules of the tickets of a project, with no screen (in the mold of projects.rs): the
//! title, the Jira ID (the same rules as `jira_id_valid` of auto_scrum.sh), the provisional
//! short UUID when there is no ID, renaming, hiding and restoring. Everything lives only in the
//! database: no function here touches a file of the project (no `.nick/docs/<ID>/` either).
//! The errors are the messages for the status bar, in PT-BR.

pub use crate::db::Ticket;

use crate::db::{Db, is_unique_violation};
use crate::projects::db_error_message;

/// How many provisional IDs are tried before giving up (plan D2).
pub const MAX_ID_ATTEMPTS: usize = 5;

/// The refusal of an invalid Jira ID: the text of auto_scrum.sh without "Tente de novo.", and
/// without the value (it may carry control characters).
pub const INVALID_ID_MESSAGE: &str = "ID do Jira inválido: não pode ter /, .., espaço nem \
     caractere de controle (ele vira o nome da pasta .nick/docs/<ID>/).";

/// When every provisional ID collided.
pub const NO_UNIQUE_ID_MESSAGE: &str =
    "Não consegui gerar um ID provisório único para o ticket. Tente de novo.";

/// The mirror of `jira_id_valid` of auto_scrum/auto_scrum.sh: the ID becomes the name of the
/// docs dir (`.nick/docs/<ID>/`), so it refuses the empty one, exactly ".", any "/", any "..",
/// any whitespace and any control character. Any change goes to both sides, with the same test
/// cases (ABOUT.md). Known difference: these are the Unicode classes, so a no-break space or a
/// C1 control is refused here even where the locale of bash would accept it (always on the side
/// of refusing more).
pub fn jira_id_valid(id: &str) -> bool {
    !(id.is_empty()
        || id == "."
        || id.contains('/')
        || id.contains("..")
        || id.chars().any(|c| c.is_whitespace() || c.is_control()))
}

/// The title, trimmed; empty or only spaces is refused.
pub fn check_title(input: &str) -> Result<&str, String> {
    let title = input.trim();
    if title.is_empty() {
        return Err("Informe o título do ticket.".into());
    }
    Ok(title)
}

/// Creates a ticket of the project: `jira_input` trimmed is the Jira ID, or, when empty, a
/// provisional short ID is generated by the database.
pub fn create(db: &Db, project_id: i64, title: &str, jira_input: &str) -> Result<Ticket, String> {
    create_with(db, project_id, title, jira_input, &mut || {
        db.random_short_id()
    })
}

/// Like `create`, with the generator of provisional IDs received by parameter (the tests make
/// it collide). A generated ID that collides is generated again, up to `MAX_ID_ATTEMPTS`.
pub fn create_with(
    db: &Db,
    project_id: i64,
    title: &str,
    jira_input: &str,
    generate: &mut dyn FnMut() -> rusqlite::Result<String>,
) -> Result<Ticket, String> {
    let title = check_title(title)?;
    let key = jira_input.trim();
    if !key.is_empty() {
        if !jira_id_valid(key) {
            return Err(INVALID_ID_MESSAGE.into());
        }
        if let Some(message) = duplicate_message(db, project_id, key)? {
            return Err(message);
        }
        return db
            .insert_ticket(project_id, key, false, title)
            .map_err(|err| {
                // Caught by the UNIQUE constraint too (another nick inserted it meanwhile).
                if is_unique_violation(&err) {
                    duplicate_message(db, project_id, key)
                        .ok()
                        .flatten()
                        .unwrap_or_else(|| visible_duplicate(key))
                } else {
                    db_error_message(&err)
                }
            });
    }
    for _ in 0..MAX_ID_ATTEMPTS {
        let key = generate().map_err(|err| db_error_message(&err))?;
        match db.insert_ticket(project_id, &key, true, title) {
            Ok(ticket) => return Ok(ticket),
            Err(err) if is_unique_violation(&err) => continue,
            Err(err) => return Err(db_error_message(&err)),
        }
    }
    Err(NO_UNIQUE_ID_MESSAGE.into())
}

fn visible_duplicate(key: &str) -> String {
    format!("Já existe um ticket com o ID {key} neste projeto.")
}

/// The refusal of a key the project already has (visible or hidden), or None.
fn duplicate_message(db: &Db, project_id: i64, key: &str) -> Result<Option<String>, String> {
    match db.find_ticket_key(project_id, key) {
        Ok(None) => Ok(None),
        Ok(Some(false)) => Ok(Some(visible_duplicate(key))),
        Ok(Some(true)) => Ok(Some(format!(
            "Já existe um ticket com o ID {key} neste projeto (oculto; f mostra os ocultos)."
        ))),
        Err(err) => Err(db_error_message(&err)),
    }
}

/// The status message after a creation.
pub fn created_message(ticket: &Ticket) -> String {
    if ticket.is_provisional {
        format!(
            "Ticket criado com o ID provisório {}: {}.",
            ticket.key, ticket.title
        )
    } else {
        format!("Ticket criado: {} — {}.", ticket.key, ticket.title)
    }
}

/// Changes the title of the ticket (the same rule as the creation); the ID never changes.
pub fn rename(db: &Db, ticket: &Ticket, title: &str) -> Result<String, String> {
    let title = check_title(title)?;
    still_there(ticket, db.update_ticket_title(ticket.id, title))?;
    Ok(format!("Título atualizado: {}.", ticket.key))
}

/// Hides the ticket: it stays in the database and can be restored.
pub fn hide(db: &Db, ticket: &Ticket) -> Result<String, String> {
    still_there(ticket, db.set_ticket_hidden(ticket.id, true))?;
    Ok(format!(
        "Ticket ocultado: {}. Ele continua no banco e pode ser restaurado (f mostra os ocultos).",
        ticket.key
    ))
}

/// Shows a hidden ticket again.
pub fn restore(db: &Db, ticket: &Ticket) -> Result<String, String> {
    still_there(ticket, db.set_ticket_hidden(ticket.id, false))?;
    Ok(format!("Ticket restaurado: {}.", ticket.key))
}

/// Turns the result of an update into the refusal of the screen: a database error, or the
/// ticket gone (another nick removed its project while this one showed it).
fn still_there(ticket: &Ticket, updated: rusqlite::Result<bool>) -> Result<(), String> {
    match updated {
        Ok(true) => Ok(()),
        Ok(false) => Err(format!("O ticket {} não existe mais no banco.", ticket.key)),
        Err(err) => Err(db_error_message(&err)),
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::projects::snapshot::snapshot;
    use std::path::{Path, PathBuf};

    // The same cases as auto_scrum/tests/test_auto_scrum.sh (section "jira_id_valid"): keep
    // both lists equal. The empty one is read_required's job in bash, and SÃO-1 is the
    // LC_ALL=C case there.
    const ACCEPTED: &[&str] = &["SC-123", "24", "ABC_1", "v1.2", "SÃO-1"];
    const REFUSED: &[&str] = &[
        ".", "..", "a/b", "../x", "a..b", "a b", "a\tb", "a\x01b", "a\x7fb", "/abs", "",
    ];

    #[test]
    fn jira_id_valid_has_the_cases_of_the_bash_suite() {
        for id in ACCEPTED {
            assert!(jira_id_valid(id), "accepts {id:?}");
        }
        for id in REFUSED {
            assert!(!jira_id_valid(id), "refuses {id:?}");
        }
    }

    #[test]
    fn jira_id_valid_refuses_more_unicode_than_bash_may() {
        // The known difference (plan D3): always on the side of refusing.
        for id in ["a\u{a0}b", "a\u{85}b", "a\u{2003}b"] {
            assert!(!jira_id_valid(id), "refuses {id:?}");
        }
    }

    /// The verdict of the real `jira_id_valid` of auto_scrum.sh for `id`, under `lc_all`.
    fn bash_verdict(id: &str, lc_all: Option<&str>) -> bool {
        let script = concat!(env!("CARGO_MANIFEST_DIR"), "/../auto_scrum/auto_scrum.sh");
        assert!(Path::new(script).is_file(), "{script}");
        let mut command = std::process::Command::new("bash");
        command
            .args(["-c", r#"source "$1"; jira_id_valid "$2""#, "_", script, id])
            .stdin(std::process::Stdio::null());
        if let Some(lc) = lc_all {
            command.env("LC_ALL", lc);
        }
        let out = command.output().expect("bash runs");
        assert!(
            out.stdout.is_empty() && out.stderr.is_empty(),
            "{id:?}: {out:?}"
        );
        match out.status.code() {
            Some(0) => true,
            Some(1) => false,
            other => panic!("{id:?}: unexpected exit {other:?}: {out:?}"),
        }
    }

    /// The rule is duplicated (ABOUT.md): the real bash function must give the same verdict
    /// as the Rust one on every case, with the inherited locale and with LC_ALL=C.
    #[test]
    fn jira_id_valid_agrees_with_the_bash_function() {
        for lc_all in [None, Some("C")] {
            for id in ACCEPTED.iter().chain(REFUSED) {
                assert_eq!(
                    bash_verdict(id, lc_all),
                    jira_id_valid(id),
                    "{id:?} with LC_ALL={lc_all:?}"
                );
            }
        }
    }

    struct Fixture {
        _tmp: tempfile::TempDir,
        root: PathBuf,
        db: Db,
        project: i64,
    }

    fn fixture() -> Fixture {
        let tmp = tempfile::tempdir().unwrap();
        let root = std::fs::canonicalize(tmp.path()).unwrap();
        let db = Db::open(&root.join("nick.db")).unwrap();
        let project = db
            .insert_project("auto_scrum", "p", root.join("p").to_str().unwrap())
            .unwrap()
            .id;
        Fixture {
            _tmp: tmp,
            root,
            db,
            project,
        }
    }

    impl Fixture {
        fn create(&self, title: &str, jira: &str) -> Result<Ticket, String> {
            create(&self.db, self.project, title, jira)
        }

        fn all(&self) -> Vec<Ticket> {
            self.db.list_tickets(self.project, true).unwrap()
        }
    }

    #[test]
    fn check_title_trims_and_refuses_blank() {
        assert_eq!(check_title("  Título  "), Ok("Título"));
        for blank in ["", "   ", "\t \n"] {
            assert_eq!(
                check_title(blank),
                Err("Informe o título do ticket.".into()),
                "{blank:?}"
            );
        }
    }

    #[test]
    fn a_blank_title_is_refused_and_nothing_is_stored() {
        let f = fixture();
        assert_eq!(
            f.create("   ", "NS-1"),
            Err("Informe o título do ticket.".into())
        );
        assert_eq!(f.all(), []);
    }

    #[test]
    fn with_an_id_it_stores_it_trimmed_and_not_provisional() {
        let f = fixture();
        let t = f.create("  Corrigir o login 🚀 ", "  NS-7  ").unwrap();
        assert_eq!(t.key, "NS-7");
        assert!(!t.is_provisional);
        assert_eq!(t.title, "Corrigir o login 🚀");
        assert_eq!(
            created_message(&t),
            "Ticket criado: NS-7 — Corrigir o login 🚀."
        );
        assert_eq!(f.all(), [t]);
    }

    #[test]
    fn an_invalid_id_is_refused_without_echoing_it() {
        let f = fixture();
        for bad in ["a/b", "..", " . ", "a b", "a\x1b[2Jb"] {
            let err = f.create("t", bad).unwrap_err();
            assert_eq!(err, INVALID_ID_MESSAGE, "{bad:?}");
            assert_eq!(
                err,
                "ID do Jira inválido: não pode ter /, .., espaço nem caractere de controle \
                 (ele vira o nome da pasta .nick/docs/<ID>/)."
            );
        }
        assert_eq!(f.all(), []);
    }

    #[test]
    fn a_repeated_id_is_refused_visible_or_hidden() {
        let f = fixture();
        f.create("a", "NS-1").unwrap();
        let hidden = f.create("b", "NS-2").unwrap();
        hide(&f.db, &hidden).unwrap();
        assert_eq!(
            f.create("c", "NS-1"),
            Err("Já existe um ticket com o ID NS-1 neste projeto.".into())
        );
        assert_eq!(
            f.create("c", " NS-2 "),
            Err(
                "Já existe um ticket com o ID NS-2 neste projeto (oculto; f mostra os ocultos)."
                    .into()
            )
        );
        assert_eq!(f.all().len(), 2);
        // The same ID in another project is fine.
        let other = f.db.insert_project("auto_scrum", "q", "/q").unwrap();
        create(&f.db, other.id, "c", "NS-1").unwrap();
    }

    #[test]
    fn without_an_id_it_generates_a_provisional_one() {
        let f = fixture();
        let t = f.create("Sem ID", "   ").unwrap();
        assert!(t.is_provisional);
        assert_eq!(t.key.len(), 8);
        assert!(t.key.chars().all(|c| matches!(c, '0'..='9' | 'a'..='f')));
        assert!(jira_id_valid(&t.key));
        assert_eq!(
            created_message(&t),
            format!("Ticket criado com o ID provisório {}: Sem ID.", t.key)
        );
        let stored: i64 =
            f.db.connection()
                .query_row(
                    "SELECT is_provisional FROM tickets WHERE id = ?1",
                    [t.id],
                    |row| row.get(0),
                )
                .unwrap();
        assert_eq!(stored, 1);
    }

    /// A generator that returns `ids` in order and counts the calls.
    fn scripted(
        ids: &[&str],
    ) -> (
        impl FnMut() -> rusqlite::Result<String>,
        std::rc::Rc<std::cell::Cell<usize>>,
    ) {
        let calls = std::rc::Rc::new(std::cell::Cell::new(0));
        let counter = std::rc::Rc::clone(&calls);
        let ids: Vec<String> = ids.iter().map(|s| s.to_string()).collect();
        let generate = move || {
            let n = counter.get();
            counter.set(n + 1);
            Ok(ids[n.min(ids.len() - 1)].clone())
        };
        (generate, calls)
    }

    #[test]
    fn a_collision_generates_again_and_the_third_wins() {
        let f = fixture();
        f.db.insert_ticket(f.project, "aaaaaaaa", true, "x")
            .unwrap();
        f.db.insert_ticket(f.project, "bbbbbbbb", true, "y")
            .unwrap();
        let (mut generate, calls) = scripted(&["aaaaaaaa", "bbbbbbbb", "cccccccc"]);
        let t = create_with(&f.db, f.project, "novo", "", &mut generate).unwrap();
        assert_eq!(t.key, "cccccccc");
        assert!(t.is_provisional);
        assert_eq!(calls.get(), 3);
    }

    #[test]
    fn always_colliding_gives_up_after_5_attempts_and_stores_nothing() {
        let f = fixture();
        f.db.insert_ticket(f.project, "aaaaaaaa", true, "x")
            .unwrap();
        let (mut generate, calls) = scripted(&["aaaaaaaa"]);
        assert_eq!(
            create_with(&f.db, f.project, "novo", "", &mut generate),
            Err(NO_UNIQUE_ID_MESSAGE.into())
        );
        assert_eq!(
            NO_UNIQUE_ID_MESSAGE,
            "Não consegui gerar um ID provisório único para o ticket. Tente de novo."
        );
        assert_eq!(calls.get(), MAX_ID_ATTEMPTS);
        assert_eq!(MAX_ID_ATTEMPTS, 5);
        assert_eq!(f.all().len(), 1);
    }

    #[test]
    fn a_generator_error_is_a_database_error() {
        let f = fixture();
        let mut generate = || Err(rusqlite::Error::InvalidQuery);
        let err = create_with(&f.db, f.project, "novo", "", &mut generate).unwrap_err();
        assert!(err.starts_with("Erro no banco do nick: "), "{err}");
        assert_eq!(f.all(), []);
    }

    #[test]
    fn rename_validates_the_title_and_keeps_the_id() {
        let f = fixture();
        let t = f.create("Velho", "NS-1").unwrap();
        assert_eq!(
            rename(&f.db, &t, "  "),
            Err("Informe o título do ticket.".into())
        );
        assert_eq!(f.all()[0].title, "Velho");
        assert_eq!(
            rename(&f.db, &t, "  Novo título "),
            Ok("Título atualizado: NS-1.".into())
        );
        let stored = &f.all()[0];
        assert_eq!(stored.title, "Novo título");
        assert_eq!(stored.key, "NS-1");
        assert_eq!(stored.id, t.id);
    }

    #[test]
    fn hide_and_restore() {
        let f = fixture();
        let t = f.create("t", "NS-1").unwrap();
        assert_eq!(
            hide(&f.db, &t),
            Ok(
                "Ticket ocultado: NS-1. Ele continua no banco e pode ser restaurado \
                (f mostra os ocultos)."
                    .into()
            )
        );
        assert_eq!(f.db.list_tickets(f.project, false).unwrap(), []);
        assert!(f.all()[0].hidden_at.is_some());
        assert_eq!(restore(&f.db, &t), Ok("Ticket restaurado: NS-1.".into()));
        assert_eq!(f.db.list_tickets(f.project, false).unwrap(), [t]);
    }

    /// Another nick removed the project (and its tickets) while this one showed the ticket:
    /// nothing changes, and the status bar says so instead of reporting success.
    #[test]
    fn a_ticket_gone_from_the_database_is_reported_not_updated() {
        let f = fixture();
        let t = f.create("t", "NS-1").unwrap();
        f.db.delete_project(f.project).unwrap();
        let gone = Err("O ticket NS-1 não existe mais no banco.".to_string());
        assert_eq!(rename(&f.db, &t, "Novo"), gone);
        assert_eq!(hide(&f.db, &t), gone);
        assert_eq!(restore(&f.db, &t), gone);
        assert_eq!(f.db.count_tickets(f.project).unwrap(), 0);
    }

    /// No action on a ticket touches a file of the project, nor creates `.nick/docs/<ID>/`
    /// (plan D8).
    #[test]
    fn no_action_touches_a_file_of_the_project() {
        let f = fixture();
        let dir = f.root.join("p");
        std::fs::create_dir_all(dir.join(".nick/docs/NS-0")).unwrap();
        std::fs::write(dir.join(".nick/nick.conf"), "STACK_DESCRIPTION=\"\"\n").unwrap();
        std::fs::write(dir.join(".nick/docs/NS-0/plan.md"), "# plano\n").unwrap();
        std::fs::write(dir.join("README.md"), "# p\n").unwrap();
        let before = snapshot(&dir);
        assert_eq!(before.len(), 6, "{before:?}");

        let with_id = f.create("Com ID", "NS-1").unwrap();
        let provisional = f.create("Sem ID", "").unwrap();
        rename(&f.db, &with_id, "Renomeado").unwrap();
        hide(&f.db, &with_id).unwrap();
        hide(&f.db, &provisional).unwrap();
        restore(&f.db, &with_id).unwrap();

        assert_eq!(snapshot(&dir), before);
        assert!(!dir.join(".nick/docs/NS-1").exists());
        assert!(!dir.join(".nick/docs").join(&provisional.key).exists());
    }
}
