//! The rules of the tickets of a project, with no screen (in the mold of projects.rs): the
//! title, the Jira ID (the same rules as `jira_id_valid` of auto_scrum.sh), the provisional
//! short UUID when there is no ID, renaming, hiding and restoring, the stage of the ticket and
//! its history (NS-36), and editing the ID. Everything lives only in the database, with one
//! exception: `edit_id` renames `.nick/docs/<old ID>/` to `.nick/docs/<new ID>/` (docs.rs), the
//! only write of the nick in a project; no function here creates, changes nor deletes any other
//! file of the project. The errors are the messages for the status bar, in PT-BR.

use std::path::Path;

pub use crate::db::Ticket;

use crate::agents::Stage;
use crate::db::{
    Db, KEY_OF_A_TICKET, KEY_OF_AN_EPIC, KeyKind, Owner, StageChange, is_trigger_abort,
    is_unique_violation,
};
use crate::docs::{self, Renamed};
use crate::projects::db_error_message;

/// How many provisional IDs are tried before giving up (plan D2).
pub const MAX_ID_ATTEMPTS: usize = 5;

/// The refusal of an invalid Jira ID: the text of auto_scrum.sh without "Tente de novo.", and
/// without the value (it may carry control characters).
pub const INVALID_ID_MESSAGE: &str = "ID do Jira inválido: não pode ter /, .., espaço nem \
     caractere de controle (ele vira o nome da pasta .nick/docs/<ID>/).";

/// When every provisional ID collided.
pub const NO_UNIQUE_ID_MESSAGE: &str =
    "Não consegui gerar um ID provisório único para o ticket. Tente de novo.";

/// The mirror of `jira_id_valid` of auto_scrum/auto_scrum.sh: the ID becomes the name of the
/// docs dir (`.nick/docs/<ID>/`), so it refuses the empty one, exactly ".", any "/", any "..",
/// any whitespace and any control character. Any change goes to both sides, with the same test
/// cases (ABOUT.md). Known difference: these are the Unicode classes, so a no-break space or a
/// C1 control is refused here even where the locale of bash would accept it (always on the side
/// of refusing more).
pub fn jira_id_valid(id: &str) -> bool {
    !(id.is_empty()
        || id == "."
        || id.contains('/')
        || id.contains("..")
        || id.chars().any(|c| c.is_whitespace() || c.is_control()))
}

/// The Jira link of a ticket or of an epic (NS-53): the base (the JIRA_URL of the project, from
/// `bin/nick-agent`) followed by the key, literally (no `/` added, no scheme checked: the base is
/// kept as typed). `None` without a base, with an empty one or with a provisional key (a UUID,
/// which is no ID of the Jira). The only place that joins a base and a key: the panels and the
/// forms of the stages all go through it.
pub fn jira_link(base: Option<&str>, key: &str, provisional: bool) -> Option<String> {
    let base = base.filter(|base| !base.is_empty())?;
    (!provisional).then(|| format!("{base}{key}"))
}

/// The title, trimmed; empty or only spaces is refused.
pub fn check_title(input: &str) -> Result<&str, String> {
    check_title_of(input, "ticket")
}

/// `check_title` with the noun of the refusal (NS-40: `ticket` or `épico`).
pub fn check_title_of<'a>(input: &'a str, noun: &str) -> Result<&'a str, String> {
    let title = input.trim();
    if title.is_empty() {
        return Err(format!("Informe o título do {noun}."));
    }
    Ok(title)
}

/// Creates a ticket of the project: `jira_input` trimmed is the Jira ID, or, when empty, a
/// provisional short ID is generated by the database.
pub fn create(db: &Db, project_id: i64, title: &str, jira_input: &str) -> Result<Ticket, String> {
    create_in(db, project_id, None, title, jira_input)
}

/// `create`, in the epic `epic_id` (NS-40; None: right under the project).
pub fn create_in(
    db: &Db,
    project_id: i64,
    epic_id: Option<i64>,
    title: &str,
    jira_input: &str,
) -> Result<Ticket, String> {
    create_in_with(db, project_id, epic_id, title, jira_input, &mut || {
        db.random_short_id()
    })
}

/// Like `create`, with the generator of provisional IDs received by parameter (the tests make
/// it collide). A generated ID that collides is generated again, up to `MAX_ID_ATTEMPTS`.
pub fn create_with(
    db: &Db,
    project_id: i64,
    title: &str,
    jira_input: &str,
    generate: &mut dyn FnMut() -> rusqlite::Result<String>,
) -> Result<Ticket, String> {
    create_in_with(db, project_id, None, title, jira_input, generate)
}

/// `create_in` with the generator received by parameter: the one body of the creation of a ticket
/// (review of the NS-40, P3.1).
fn create_in_with(
    db: &Db,
    project_id: i64,
    epic_id: Option<i64>,
    title: &str,
    jira_input: &str,
    generate: &mut dyn FnMut() -> rusqlite::Result<String>,
) -> Result<Ticket, String> {
    let title = check_title(title)?;
    create_key_with(
        db,
        project_id,
        jira_input,
        NO_UNIQUE_ID_MESSAGE,
        generate,
        &mut |key, provisional| db.insert_ticket(project_id, key, provisional, title, epic_id),
    )
}

/// The loop of a creation of a ticket or of an epic (NS-40, extracted from `create_with`):
/// `jira_input` trimmed is the Jira ID (valid, and not the key of a ticket nor of an epic of the
/// project), or, when empty, a provisional one by `generate`, generated again when it collides
/// (with a ticket or an epic), up to `MAX_ID_ATTEMPTS`; then `no_unique` (the message with the
/// noun of the caller). `insert` stores the row with the key and whether it is provisional. A
/// typed key caught by the UNIQUE or by a trigger (another nick stored it meanwhile) gets the
/// message of the check.
pub(crate) fn create_key_with<T>(
    db: &Db,
    project_id: i64,
    jira_input: &str,
    no_unique: &str,
    generate: &mut dyn FnMut() -> rusqlite::Result<String>,
    insert: &mut dyn FnMut(&str, bool) -> rusqlite::Result<T>,
) -> Result<T, String> {
    let key = jira_input.trim();
    if !key.is_empty() {
        if !jira_id_valid(key) {
            return Err(INVALID_ID_MESSAGE.into());
        }
        if let Some(message) = duplicate_message(db, project_id, key)? {
            return Err(message);
        }
        return insert(key, false).map_err(|err| taken_message(db, project_id, key, &err));
    }
    for _ in 0..MAX_ID_ATTEMPTS {
        let key = generate().map_err(|err| db_error_message(&err))?;
        match insert(&key, true) {
            Ok(row) => return Ok(row),
            Err(err) if key_taken(&err).is_some() => continue,
            Err(err) => return Err(db_error_message(&err)),
        }
    }
    Err(no_unique.into())
}

/// Whose the key is, when `err` says it is taken: the UNIQUE of the table (the same kind as the
/// row, unknown here) or a trigger of the migration 7 (the other kind).
fn key_taken(err: &rusqlite::Error) -> Option<Option<KeyKind>> {
    if is_unique_violation(err) {
        Some(None)
    } else if is_trigger_abort(err, KEY_OF_A_TICKET) {
        Some(Some(KeyKind::Ticket))
    } else if is_trigger_abort(err, KEY_OF_AN_EPIC) {
        Some(Some(KeyKind::Epic))
    } else {
        None
    }
}

/// The message of a write refused because `key` was taken meanwhile (the UNIQUE or a trigger),
/// read again as in the check; any other error is the error of the database.
fn taken_message(db: &Db, project_id: i64, key: &str, err: &rusqlite::Error) -> String {
    match key_taken(err) {
        Some(kind) => duplicate_message(db, project_id, key)
            .ok()
            .flatten()
            .unwrap_or_else(|| visible_duplicate(kind.unwrap_or(KeyKind::Ticket), key)),
        None => db_error_message(err),
    }
}

fn visible_duplicate(kind: KeyKind, key: &str) -> String {
    let noun = match kind {
        KeyKind::Ticket => "um ticket",
        KeyKind::Epic => "um épico",
    };
    format!("Já existe {noun} com o ID {key} neste projeto.")
}

/// The refusal of a key the project already has, of a ticket or of an epic (NS-40: both use
/// `.nick/docs/<key>/`), visible or hidden, or None.
pub(crate) fn duplicate_message(
    db: &Db,
    project_id: i64,
    key: &str,
) -> Result<Option<String>, String> {
    match db.find_key(project_id, key) {
        Ok(None) => Ok(None),
        Ok(Some((kind, false))) => Ok(Some(visible_duplicate(kind, key))),
        Ok(Some((kind, true))) => Ok(Some(format!(
            "{} (oculto; f mostra os ocultos).",
            visible_duplicate(kind, key).trim_end_matches('.')
        ))),
        Err(err) => Err(db_error_message(&err)),
    }
}

/// The status message after a creation.
pub fn created_message(ticket: &Ticket) -> String {
    if ticket.is_provisional {
        format!(
            "Ticket criado com o ID provisório {}: {}.",
            ticket.key, ticket.title
        )
    } else {
        format!("Ticket criado: {} — {}.", ticket.key, ticket.title)
    }
}

/// Changes the title of the ticket (the same rule as the creation); the ID never changes.
pub fn rename(db: &Db, ticket: &Ticket, title: &str) -> Result<String, String> {
    let title = check_title(title)?;
    still_there(ticket, db.update_ticket_title(ticket.id, title))?;
    Ok(format!("Título atualizado: {}.", ticket.key))
}

/// Hides the ticket: it stays in the database and can be restored.
pub fn hide(db: &Db, ticket: &Ticket) -> Result<String, String> {
    still_there(ticket, db.set_ticket_hidden(ticket.id, true))?;
    Ok(format!(
        "Ticket ocultado: {}. Ele continua no banco e pode ser restaurado (f mostra os ocultos).",
        ticket.key
    ))
}

/// Shows a hidden ticket again.
pub fn restore(db: &Db, ticket: &Ticket) -> Result<String, String> {
    still_there(ticket, db.set_ticket_hidden(ticket.id, false))?;
    Ok(format!("Ticket restaurado: {}.", ticket.key))
}

/// Turns the result of an update into the refusal of the screen: a database error, or the
/// ticket gone (another nick removed its project while this one showed it).
fn still_there(ticket: &Ticket, updated: rusqlite::Result<bool>) -> Result<(), String> {
    match updated {
        Ok(true) => Ok(()),
        Ok(false) => Err(gone_message(ticket)),
        Err(err) => Err(db_error_message(&err)),
    }
}

/// The ticket is no longer in the database.
pub fn gone_message(ticket: &Ticket) -> String {
    format!("O ticket {} não existe mais no banco.", ticket.key)
}

/// The stage of a ticket (NS-36): "Aberto" (NS-45), the four stages of the agents, then
/// "Concluído". The declaration order is the order of the flow, and `Ord` follows it. Changed by
/// the operator (`change_stage`), to any stage, and by the opening of a new agent of a later stage
/// (`advance_on_agent_opening`, NS-45): it opens, closes and hides no agent.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
pub enum TicketStage {
    Open,
    Po,
    TechLeader,
    Development,
    Review,
    Done,
}

impl From<Stage> for TicketStage {
    fn from(stage: Stage) -> TicketStage {
        match stage {
            Stage::Po => TicketStage::Po,
            Stage::TechLeader => TicketStage::TechLeader,
            Stage::Development => TicketStage::Development,
            Stage::Review => TicketStage::Review,
        }
    }
}

impl TicketStage {
    /// Every stage, in the order of the flow (the order of the dialog).
    pub const ALL: [TicketStage; 6] = [
        TicketStage::Open,
        TicketStage::Po,
        TicketStage::TechLeader,
        TicketStage::Development,
        TicketStage::Review,
        TicketStage::Done,
    ];

    /// The stage of the agents with the same key and label; None for `Open` and `Done`, the
    /// stages only of the ticket.
    pub fn agent_stage(self) -> Option<Stage> {
        match self {
            TicketStage::Po => Some(Stage::Po),
            TicketStage::TechLeader => Some(Stage::TechLeader),
            TicketStage::Development => Some(Stage::Development),
            TicketStage::Review => Some(Stage::Review),
            TicketStage::Open | TicketStage::Done => None,
        }
    }

    /// The key stored in `tickets.stage` and in the history.
    pub fn key(self) -> &'static str {
        match self {
            TicketStage::Open => "open",
            TicketStage::Po => Stage::Po.key(),
            TicketStage::TechLeader => Stage::TechLeader.key(),
            TicketStage::Development => Stage::Development.key(),
            TicketStage::Review => Stage::Review.key(),
            TicketStage::Done => "done",
        }
    }

    /// What the screen shows.
    pub fn label(self) -> &'static str {
        match self {
            TicketStage::Open => "Aberto",
            TicketStage::Po => Stage::Po.label(),
            TicketStage::TechLeader => Stage::TechLeader.label(),
            TicketStage::Development => Stage::Development.label(),
            TicketStage::Review => Stage::Review.label(),
            TicketStage::Done => "Concluído",
        }
    }

    /// The stage of a stored key.
    pub fn from_key(key: &str) -> Option<TicketStage> {
        TicketStage::ALL
            .into_iter()
            .find(|stage| stage.key() == key)
    }
}

/// The label of a stored stage key, or the key itself when it is unknown (the CHECK of the
/// schema keeps it from happening; the screen never panics on it).
pub fn stage_label(key: &str) -> String {
    TicketStage::from_key(key).map_or_else(|| key.to_string(), |stage| stage.label().into())
}

/// Who changed the stage of a ticket (NS-45), stored in `ticket_stage_changes.source`: the
/// operator, by the dialog, or the opening of a new agent of a later stage.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum StageSource {
    Operator,
    AgentOpening,
}

impl StageSource {
    /// Every source.
    pub const ALL: [StageSource; 2] = [StageSource::Operator, StageSource::AgentOpening];

    /// The key stored in the history.
    pub fn key(self) -> &'static str {
        match self {
            StageSource::Operator => "operator",
            StageSource::AgentOpening => "agent_opening",
        }
    }

    /// What the screen shows.
    pub fn label(self) -> &'static str {
        match self {
            StageSource::Operator => "operador",
            StageSource::AgentOpening => "abertura de agente",
        }
    }

    /// The source of a stored key.
    pub fn from_key(key: &str) -> Option<StageSource> {
        StageSource::ALL
            .into_iter()
            .find(|source| source.key() == key)
    }
}

/// The label of a stored source key, or the key itself when it is unknown (as `stage_label`).
pub fn source_label(key: &str) -> String {
    StageSource::from_key(key).map_or_else(|| key.to_string(), |source| source.label().into())
}

/// The refusal of changing the ticket to the stage it is already at.
pub fn same_stage_message(ticket: &Ticket, to: TicketStage) -> String {
    format!("O ticket {} já está em {}.", ticket.key, to.label())
}

/// Changes the stage of the ticket to `to`, with its row in the history, by the operator (one
/// transaction: `Db::change_ticket_stage`). Only the confirmation of the dialog of the node of a
/// ticket calls it; the other writer is `advance_on_agent_opening` (NS-45). The same stage is
/// refused; a ticket gone, or moved by another nick meanwhile, stores nothing.
pub fn change_stage(db: &Db, ticket: &Ticket, to: TicketStage) -> Result<String, String> {
    if ticket.stage == to.key() {
        return Err(same_stage_message(ticket, to));
    }
    match db.change_ticket_stage(
        ticket.id,
        &ticket.stage,
        to.key(),
        StageSource::Operator.key(),
    ) {
        Ok(StageChange::Changed) => Ok(format!(
            "Etapa do ticket {}: {} → {}.",
            ticket.key,
            stage_label(&ticket.stage),
            to.label()
        )),
        Ok(StageChange::Gone) => Err(gone_message(ticket)),
        Ok(StageChange::Moved) => Err(format!(
            "A etapa do ticket {} mudou em outro nick. Nada foi gravado.",
            ticket.key
        )),
        Err(err) => Err(db_error_message(&err)),
    }
}

/// The advance of the stage on the opening of a new agent (NS-45, plan D4): a new agent of a
/// stage later than the one of the ticket moves the ticket to it, even skipping stages, with the
/// source `agent_opening` in the history. The same or an earlier stage, `Done`, an unknown key and
/// a ticket gone change nothing (`Ok(None)`). Called only by `App::open_agent`, after the agent
/// was spawned, for an agent of a ticket. The message is for the status bar.
pub fn advance_on_agent_opening(
    db: &Db,
    ticket_id: i64,
    stage: Stage,
) -> Result<Option<String>, String> {
    advance_on_agent_opening_with(db, ticket_id, stage, &mut |id| db.get_ticket(id))
}

/// `advance_on_agent_opening` with the read of the ticket received by parameter (the tests make
/// another nick move it between the read and the write). The ticket is read from the database,
/// because the stage may have changed in another nick.
fn advance_on_agent_opening_with(
    db: &Db,
    ticket_id: i64,
    stage: Stage,
    read: &mut dyn FnMut(i64) -> rusqlite::Result<Option<Ticket>>,
) -> Result<Option<String>, String> {
    let Some(ticket) = read(ticket_id).map_err(|err| db_error_message(&err))? else {
        return Ok(None);
    };
    let Some(current) = TicketStage::from_key(&ticket.stage) else {
        return Ok(None);
    };
    let to = TicketStage::from(stage);
    if current == TicketStage::Done || to <= current {
        return Ok(None);
    }
    match db.change_ticket_stage(
        ticket.id,
        current.key(),
        to.key(),
        StageSource::AgentOpening.key(),
    ) {
        Ok(StageChange::Changed) => Ok(Some(format!(
            "Etapa do ticket {}: {} → {} ({}).",
            ticket.key,
            current.label(),
            to.label(),
            StageSource::AgentOpening.label()
        ))),
        Ok(StageChange::Moved) => Err(format!(
            "A etapa do ticket {} mudou em outro nick. A etapa não avançou.",
            ticket.key
        )),
        Ok(StageChange::Gone) => Ok(None),
        Err(err) => Err(db_error_message(&err)),
    }
}

/// Steps 1 to 5 of "Editar ID" (plan D5 of NS-36), with nothing written: the new ID trimmed
/// (as in the creation), not empty, accepted by `jira_id_valid`, different from the current
/// one, not in the project (visible or hidden), and no `active` agent of the ticket (of this
/// nick or of another one: their prompt cites the docs dir). Returns the new ID.
pub fn check_new_id(db: &Db, ticket: &Ticket, input: &str) -> Result<String, String> {
    check_new_key(
        db,
        ticket.project_id,
        &ticket.key,
        input,
        "ticket",
        Owner::Ticket(ticket.id),
    )
}

/// The checks 1 to 5 of "Editar ID" of a ticket or of an epic (NS-40, extracted from
/// `check_new_id`): `noun` names it in the refusals, and `owner` is whose `active` agents block
/// the edit (of an epic, only its own: the agents of its tickets cite the folder of the ticket).
pub(crate) fn check_new_key(
    db: &Db,
    project_id: i64,
    current: &str,
    input: &str,
    noun: &str,
    owner: Owner,
) -> Result<String, String> {
    let new = input.trim();
    if new.is_empty() {
        return Err(format!("Informe o novo ID do {noun}."));
    }
    if !jira_id_valid(new) {
        return Err(INVALID_ID_MESSAGE.into());
    }
    if new == current {
        return Err("O ID não mudou.".into());
    }
    if let Some(message) = duplicate_message(db, project_id, new)? {
        return Err(message);
    }
    match db.count_active_agents(owner) {
        Ok(0) => Ok(new.to_string()),
        Ok(_) => Err(format!(
            "O {noun} {current} tem agente ativo. Encerre os agentes dele antes de editar o ID: o \
             prompt deles cita a pasta {}.",
            docs::dir_text(current)
        )),
        Err(err) => Err(db_error_message(&err)),
    }
}

/// Edits the ID of the ticket of the project at `project` (plan D5 of NS-36).
pub fn edit_id(db: &Db, project: &Path, ticket: &Ticket, input: &str) -> Result<String, String> {
    edit_id_with(db, project, ticket, input, &mut |old, new| {
        db.update_ticket_key(ticket.id, old, new)
    })
}

/// `edit_id` with the write of the database received by parameter (the tests make it fail).
/// The checks run again (the state may have changed since the dialog), then the folder
/// `.nick/docs/<old>/` is renamed first (`docs::rename`, never replacing anything) and the
/// database is written after; a failing database undoes the rename. A failing undo is told
/// with where the folder is; nothing is ever removed nor merged to "fix" it.
pub fn edit_id_with(
    db: &Db,
    project: &Path,
    ticket: &Ticket,
    input: &str,
    update: &mut dyn FnMut(&str, &str) -> rusqlite::Result<bool>,
) -> Result<String, String> {
    let new = check_new_id(db, ticket, input)?;
    rename_key_with(
        db,
        project,
        ticket.project_id,
        &ticket.key,
        &new,
        &gone_message(ticket),
        "o ticket",
        update,
    )
}

/// The core of "Editar ID" of a ticket or of an epic (NS-40, extracted from `edit_id_with`), after
/// the checks: the folder `.nick/docs/<old>/` renamed first, the database written after by
/// `update`, and the rename undone when it fails (`gone` is the message of a row gone, and
/// `whose` names the row in the message of a failing undo: `o ticket`, `o épico`).
#[allow(clippy::too_many_arguments)]
pub(crate) fn rename_key_with(
    db: &Db,
    project: &Path,
    project_id: i64,
    old: &str,
    new: &str,
    gone: &str,
    whose: &str,
    update: &mut dyn FnMut(&str, &str) -> rusqlite::Result<bool>,
) -> Result<String, String> {
    let renamed = docs::rename(project, old, new)?;
    let failure = match update(old, new) {
        Ok(true) => {
            let mut message = format!("ID atualizado: {old} → {new}.");
            if renamed == Renamed::Moved {
                message = format!(
                    "{message} A pasta {} virou {}.",
                    docs::dir_text(old),
                    docs::dir_text(new)
                );
            }
            return Ok(message);
        }
        Ok(false) => gone.to_string(),
        Err(err) => taken_message(db, project_id, new, &err),
    };
    if renamed == Renamed::NoFolder {
        return Err(failure);
    }
    match docs::undo_rename(project, old, new) {
        Ok(()) => Err(format!(
            "{failure} A pasta voltou para {}.",
            docs::dir_text(old)
        )),
        Err(err) => Err(format!(
            "{failure} Não consegui desfazer a renomeação: a pasta está em {} e {whose} \
             continua com o ID {old}. {err}.",
            docs::dir_text(new)
        )),
    }
}

